import { chromium } from '/home/user/CN-Project/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ executablePath: '/tmp/browser/out/chromium', args: ['--no-sandbox','--disable-dev-shm-usage','--disable-gpu'] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
await page.goto('http://127.0.0.1:1420/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
await page.getByRole('button', { name: 'Batch Experiments', exact: true }).click();
await page.waitForTimeout(1000);
await page.getByLabel('Sweep Values List (comma-separated numbers)').fill('1000000, 10000000');
await page.getByLabel('PRNG Seeds (comma-separated)').fill('42');
await page.getByRole('button', { name: 'Execute Parameter Sweep' }).click();
await page.waitForTimeout(12000);
console.log('sweep runs present:', await page.getByText('Total Simulated Runs').count());
// download JSON
const dl1 = page.waitForEvent('download');
await page.getByRole('button', { name: 'JSON', exact: true }).first().click();
const d1 = await dl1;
await d1.saveAs('/tmp/verify/dl/sweep.json');
console.log('sweep json saved:', d1.suggestedFilename());
const dl2 = page.waitForEvent('download');
await page.getByRole('button', { name: 'CSV', exact: true }).first().click();
const d2 = await dl2;
await d2.saveAs('/tmp/verify/dl/sweep.csv');
console.log('sweep csv saved:', d2.suggestedFilename());
// A/B tab
await page.getByRole('button', { name: 'Comparative A/B' }).click();
await page.waitForTimeout(800);
await page.getByRole('button', { name: 'Run Comparative A/B Test' }).click();
await page.waitForTimeout(12000);
console.log('ab deltas present:', await page.getByText(/Comparative Metric Deltas/).count());
const dl3 = page.waitForEvent('download');
await page.getByRole('button', { name: 'JSON', exact: true }).first().click();
const d3 = await dl3;
await d3.saveAs('/tmp/verify/dl/ab.json');
console.log('ab json saved:', d3.suggestedFilename());
const dl4 = page.waitForEvent('download');
await page.getByRole('button', { name: 'CSV', exact: true }).first().click();
const d4 = await dl4;
await d4.saveAs('/tmp/verify/dl/ab.csv');
console.log('ab csv saved:', d4.suggestedFilename());
await page.screenshot({ path: '/tmp/verify/shots/v-exp.png' });
await browser.close();
console.log('done');
